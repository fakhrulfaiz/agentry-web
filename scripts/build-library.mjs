#!/usr/bin/env node
/**
 * Bundles the built-in agent library (`src/agents/library/*.md`, except NOTICE.md) into
 * `src/agents/library/files.generated.ts`, so the web app ships the files as text.
 * Run after editing a library file: `pnpm library:build` (a unit test fails while they differ).
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const dir = join(import.meta.dirname, '..', 'src', 'agents', 'library')

/** The generated module's text for the current library files. */
export function generate() {
  const files = readdirSync(dir).filter((f) => f.endsWith('.md') && f !== 'NOTICE.md').sort()
  const entries = files.map((file) => `  { file: ${JSON.stringify(file)}, text: ${JSON.stringify(readFileSync(join(dir, file), 'utf8'))} },`)
  return [
    '// Generated by scripts/build-library.mjs from src/agents/library/*.md. Do not edit; run `pnpm library:build`.',
    '',
    '/** The built-in library files: file name and full text (front matter plus prompt). */',
    'export const LIBRARY_FILES: ReadonlyArray<{ file: string; text: string }> = [',
    ...entries,
    ']',
    '',
  ].join('\n')
}

if (import.meta.url === `file://${process.argv[1]}`) {
  writeFileSync(join(dir, 'files.generated.ts'), generate())
  console.log('wrote src/agents/library/files.generated.ts')
}
